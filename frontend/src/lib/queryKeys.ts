/**
 * Every React Query key in the application, by root.
 *
 * A key is an array whose first element names the cache family: the pages
 * read `queryKeys.contracts(id)` and invalidate `queryKeys.contracts()`, so a
 * family's spelling lives here once and a typo in an invalidation is a type
 * error rather than a cache that silently never refreshes. The arrays are the
 * same ones the pages used to write inline — `queryKeys.time("week", start)`
 * is `["time", "week", start]` — so prefix invalidation works exactly as
 * before: `queryKeys.time()` matches every key under `"time"`.
 *
 * Domain modules may build richer helpers on top (`features/<x>/queries.ts`)
 * as each feature is refactored; they should start from these roots.
 */

/** A key family: called with no parts it is the prefix that matches them all. */
function root<R extends string>(name: R) {
  return <const P extends readonly unknown[]>(...parts: P) => [name, ...parts] as const;
}

