// The bulk-edit grid, used and abandoned (nothing saved): type into a cell,
// Escape to cancel, edit + Enter, undo/redo, fill down, paste a block, an
// invalid value, Discard. Screens and console per step.   node e2e/audit-b/grid.mjs
import path from "node:path";
import { BASE, SHOTS, axe, context, launch, settle, watch } from "./lib.mjs";

const browser = await launch();
const ctx = await context(browser, {});
await ctx.grantPermissions(["clipboard-read", "clipboard-write"], { origin: BASE });
const page = await ctx.newPage();
const log = watch(page);
const shot = (n) => page.screenshot({ path: path.join(SHOTS, `auditB_grid_${n}_pc_light.png`) });
const pending = async () => (await page.getByTestId("grid-pending").innerText().catch(() => "none"));
await page.goto(BASE + "/customers/grid");
await page.getByTestId("record-grid").waitFor({ timeout: 60_000 });
await settle(page, 800);
const grid = page.getByTestId("record-grid");
await grid.click({ position: { x: 300, y: 60 } });
await page.keyboard.press("ArrowRight");
await page.keyboard.type("zzauditB typed");
await page.waitForTimeout(300);
await shot("1-typing");
await page.keyboard.press("Escape");
await page.waitForTimeout(300);
console.log("after Escape while typing, pending:", await pending());
await page.keyboard.press("Enter");
await page.keyboard.type("zzauditB edit");
await page.keyboard.press("Enter");
await page.waitForTimeout(300);
console.log("after edit+Enter, pending:", await pending());
await shot("2-edited");
await page.keyboard.press("Control+z");
await page.waitForTimeout(200);
console.log("after undo, pending:", await pending());
await page.keyboard.press("Control+y");
await page.waitForTimeout(200);
console.log("after redo, pending:", await pending());
await page.keyboard.press("Shift+ArrowDown");
await page.keyboard.press("Shift+ArrowDown");
await page.keyboard.press("Control+d");
await page.waitForTimeout(300);
console.log("after fill down, pending:", await pending());
await shot("3-filldown");
await page.evaluate(() => navigator.clipboard.writeText("a\tb\nc\td"));
await page.keyboard.press("ArrowDown");
await page.keyboard.press("Control+v");
await page.waitForTimeout(500);
console.log("after paste, pending:", await pending(), "invalid:", await page.getByTestId("grid-invalid").innerText().catch(() => "none"));
await shot("4-paste");
const ax = await axe(page);
console.log("axe:", ax.map((v) => `${v.id}(${v.n}) ${v.targets[0]}`).join(" | ") || "clean");
await page.getByRole("button", { name: "Discard" }).click();
await page.waitForTimeout(500);
const confirm = page.locator(".ant-popconfirm .ant-btn-primary, .ant-modal-confirm .ant-btn-primary").filter({ visible: true }).last();
if (await confirm.count()) await confirm.click();
await page.waitForTimeout(500);
console.log("after discard, pending:", await pending());
await shot("5-discarded");
// Leaving with nothing pending must not ask; leaving with edits should.
await page.keyboard.press("Enter");
await page.keyboard.type("zzauditB leave");
await page.keyboard.press("Enter");
page.once("dialog", (d) => { console.log("leave dialog:", d.message().slice(0, 80)); d.dismiss(); });
await page.getByRole("button", { name: /Back to the list/ }).click();
await page.waitForTimeout(800);
console.log("url after Back with pending edit:", page.url().replace(BASE, ""), "modal:", await page.locator(".ant-modal").filter({ visible: true }).count());
await shot("6-leave");
console.log("console:", log.console, log.pageErrors);
await browser.close();
